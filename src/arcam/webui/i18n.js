// t() 与 Python 侧同语义：{0} 占位符、缺 key 回落裸 key、lang 非 en 即中文。
window.arcamT = function (key) {
  var pair = window.ARCAM_TXT[key];
  if (!pair) return key;
  var lang = (window.ARCAM_LANG === "en") ? 1 : 0;
  var text = pair[lang];
  for (var i = 1; i < arguments.length; i++) {
    text = text.split("{" + (i - 1) + "}").join(String(arguments[i]));
  }
  return text;
};
